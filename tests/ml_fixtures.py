"""Tiny ONNX models and tokenizers, generated at test time (no binaries are committed, no weights downloaded).

- token classifier: input_ids -> Gather(E[V, H]) -> MatMul(W[H, L]) + b -> logits [B, T, L]. E and W are randomly
  initialised (seeded); a few vocabulary rows are then set so chosen words get chosen labels, which makes decoding,
  offsets and windows testable. ``random_only=True`` keeps the purely random weights.
- sequence classifier (content gate): Gather -> ReduceMax over tokens -> MatMul -> logits [B, C].
- GLiNER-style span model: the six GLiNER inputs; logits [B, W, K, C] depend on the span mask and the span width only.
- WordPiece tokenizer.json built with the `tokenizers` library (lower-casing BERT normaliser and pre-tokeniser).

Factories for the worker-pool tests (slow, crashing, failing to start) are at the bottom; worker processes import
them by name ("tests.ml_fixtures:slow_detector").
"""
from __future__ import annotations

import json
import os
import time
from pathlib import Path

import numpy as np

SPECIAL = ["[PAD]", "[UNK]", "[CLS]", "[SEP]", "<<ENT>>", "<<SEP>>"]
WORDS = ["priya", "nair", "rahul", "sharma", "rag", "##hu", "##nathan", "mumbai", "met", "with", "and", "in",
         "the", "hello", "email", "at", "on", "for", "leave", "request", "diagnosis", "cancer", "union", "salary",
         "team", "meeting", "today", "person", "location", ".", ",", "@", ":", "-", "!", "?"]
VOCAB = {t: i for i, t in enumerate(SPECIAL + WORDS)}
ID2LABEL = ["O", "B-PER", "I-PER", "B-LOC", "I-LOC"]
TOKEN_ROLES = {"priya": "B-PER", "rahul": "B-PER", "rag": "B-PER", "nair": "I-PER", "sharma": "I-PER",
               "mumbai": "B-LOC"}
GATE_LABELS = ["health", "union_membership", "disciplinary"]
GATE_ROLES = {"diagnosis": "health", "cancer": "health", "union": "union_membership"}
SPAN_LABELS = ["person", "location"]
CARD = "# Test model\n\nRandomly initialised; generated by tests/ml_fixtures.py. Not a real model. Licence: n/a.\n"


def tokenizer_json() -> str:
    from tokenizers import Tokenizer, decoders, models, normalizers, pre_tokenizers
    tok = Tokenizer(models.WordPiece(VOCAB, unk_token="[UNK]", max_input_chars_per_word=100))
    tok.normalizer = normalizers.BertNormalizer(lowercase=True, strip_accents=True, clean_text=True)
    tok.pre_tokenizer = pre_tokenizers.BertPreTokenizer()
    tok.decoder = decoders.WordPiece()
    return tok.to_str()


def _write(d: Path, model, labels: dict, extra: dict | None = None) -> tuple[Path, str]:
    import onnx
    from pgw.ml.artifact import digest_dir
    d.mkdir(parents=True, exist_ok=True)
    onnx.checker.check_model(model)
    (d / "model.onnx").write_bytes(model.SerializeToString())
    (d / "tokenizer.json").write_text(tokenizer_json(), encoding="utf-8")
    (d / "labels.json").write_text(json.dumps(labels), encoding="utf-8")
    (d / "MODEL_CARD.md").write_text(CARD, encoding="utf-8")
    for name, data in (extra or {}).items():
        (d / name).write_bytes(data)
    return d, digest_dir(d)[0]


def _graph_model(nodes, inputs, outputs, inits, opset: int = 17):
    from onnx import helper
    g = helper.make_graph(nodes, "tiny", inputs, outputs, inits)
    m = helper.make_model(g, opset_imports=[helper.make_opsetid("", opset)], producer_name="pgw-tests")
    m.ir_version = 8
    return m


def token_model(random_only: bool = False, seed: int = 0, n_labels: int | None = None):
    from onnx import TensorProto, helper, numpy_helper
    rng = np.random.default_rng(seed)
    L = n_labels or len(ID2LABEL)
    V, H = len(VOCAB), L
    E = rng.normal(0, 0.1, (V, H)).astype(np.float32)
    W = (np.eye(H) + rng.normal(0, 0.01, (H, L))).astype(np.float32)
    b = np.zeros(L, dtype=np.float32)
    if not random_only:
        E[:, :] = rng.normal(0, 0.1, (V, H))
        E[:, 0] += 4.0                                   # every token: "O" unless set below
        for tok, lab in TOKEN_ROLES.items():
            E[VOCAB[tok], 0] -= 4.0
            E[VOCAB[tok], ID2LABEL.index(lab)] += 5.0
    nodes = [helper.make_node("Gather", ["E", "input_ids"], ["emb"], axis=0),
             helper.make_node("MatMul", ["emb", "W"], ["mm"]),
             helper.make_node("Add", ["mm", "b"], ["logits"])]
    inputs = [helper.make_tensor_value_info("input_ids", TensorProto.INT64, ["batch", "seq"]),
              helper.make_tensor_value_info("attention_mask", TensorProto.INT64, ["batch", "seq"])]
    outputs = [helper.make_tensor_value_info("logits", TensorProto.FLOAT, ["batch", "seq", L])]
    inits = [numpy_helper.from_array(E, "E"), numpy_helper.from_array(W, "W"), numpy_helper.from_array(b, "b")]
    return _graph_model(nodes, inputs, outputs, inits)


def make_token_model(d: Path, *, quantize: bool = False, random_only: bool = False, max_length: int = 16,
                     stride: int = 4, scheme: str = "BIO", aggregation: str = "first", specials: bool = True,
                     id2label: list[str] | None = None, extra: dict | None = None) -> tuple[Path, str]:
    model = token_model(random_only=random_only, n_labels=len(id2label) if id2label else None)
    if quantize:
        model = _quantize(model, d)
    labels = {"format": "pgw-ml-labels/1", "task": "token-classification", "id2label": id2label or ID2LABEL,
              "scheme": scheme, "max_length": max_length, "stride": stride, "aggregation": aggregation}
    if specials:
        labels["special_tokens"] = {"cls": "[CLS]", "sep": "[SEP]", "pad": "[PAD]"}
    return _write(d, model, labels, extra)


def _quantize(model, d: Path):
    import onnx
    from onnxruntime.quantization import QuantType, quantize_dynamic
    tmp = d.parent / (d.name + ".fp32.onnx")
    out = d.parent / (d.name + ".int8.onnx")
    d.parent.mkdir(parents=True, exist_ok=True)
    onnx.save(model, tmp)
    quantize_dynamic(str(tmp), str(out), weight_type=QuantType.QInt8)
    q = onnx.load(str(out))
    tmp.unlink()
    out.unlink()
    return q


def gate_model():
    from onnx import TensorProto, helper, numpy_helper
    C = len(GATE_LABELS)
    rng = np.random.default_rng(1)
    E = (rng.normal(0, 0.1, (len(VOCAB), C)) - 6.0).astype(np.float32)
    for tok, lab in GATE_ROLES.items():
        E[VOCAB[tok], GATE_LABELS.index(lab)] = 6.0
    W = np.eye(C, dtype=np.float32)
    nodes = [helper.make_node("Gather", ["E", "input_ids"], ["emb"], axis=0),
             helper.make_node("ReduceMax", ["emb"], ["pooled"], axes=[1], keepdims=0),
             helper.make_node("MatMul", ["pooled", "W"], ["logits"])]
    inputs = [helper.make_tensor_value_info("input_ids", TensorProto.INT64, ["batch", "seq"]),
              helper.make_tensor_value_info("attention_mask", TensorProto.INT64, ["batch", "seq"])]
    outputs = [helper.make_tensor_value_info("logits", TensorProto.FLOAT, ["batch", C])]
    return _graph_model(nodes, inputs, outputs, [numpy_helper.from_array(E, "E"), numpy_helper.from_array(W, "W")])


def make_gate_model(d: Path, *, max_length: int = 16, stride: int = 4, labels: list[str] | None = None,
                    quantize: bool = False) -> tuple[Path, str]:
    model = gate_model()
    if quantize:
        model = _quantize(model, d)
    doc = {"format": "pgw-ml-labels/1", "task": "sequence-classification", "labels": labels or GATE_LABELS,
           "problem_type": "multi_label", "max_length": max_length, "stride": stride,
           "special_tokens": {"cls": "[CLS]", "sep": "[SEP]", "pad": "[PAD]"}}
    return _write(d, model, doc)


def span_model(max_width: int, width_logits: list[list[float]]):
    """logits[b, i, k, c] = span_mask(i, k) * width_logits[k][c] - 8 * (1 - span_mask)."""
    from onnx import TensorProto, helper, numpy_helper
    C = len(width_logits[0])
    Wk = np.asarray(width_logits, dtype=np.float32).reshape(max_width, C)
    nodes = [helper.make_node("Cast", ["span_mask"], ["mf"], to=TensorProto.FLOAT),
             helper.make_node("Reshape", ["mf", "shape"], ["m4"]),
             helper.make_node("Mul", ["m4", "Wk"], ["pos"]),
             helper.make_node("Sub", ["m4", "one"], ["neg1"]),
             helper.make_node("Mul", ["neg1", "eight"], ["neg"]),
             helper.make_node("Add", ["pos", "neg"], ["logits"])]
    inputs = [helper.make_tensor_value_info("input_ids", TensorProto.INT64, ["batch", "seq"]),
              helper.make_tensor_value_info("attention_mask", TensorProto.INT64, ["batch", "seq"]),
              helper.make_tensor_value_info("words_mask", TensorProto.INT64, ["batch", "seq"]),
              helper.make_tensor_value_info("text_lengths", TensorProto.INT64, ["batch", 1]),
              helper.make_tensor_value_info("span_idx", TensorProto.INT64, ["batch", "spans", 2]),
              helper.make_tensor_value_info("span_mask", TensorProto.BOOL, ["batch", "spans"])]
    outputs = [helper.make_tensor_value_info("logits", TensorProto.FLOAT, ["batch", "words", max_width, C])]
    inits = [numpy_helper.from_array(np.array([0, -1, max_width, 1], dtype=np.int64), "shape"),
             numpy_helper.from_array(Wk, "Wk"), numpy_helper.from_array(np.float32(1.0).reshape(()), "one"),
             numpy_helper.from_array(np.float32(8.0).reshape(()), "eight")]
    return _graph_model(nodes, inputs, outputs, inits)


def make_span_model(d: Path, *, max_width: int = 3, max_words: int = 8, max_length: int = 64,
                    width_logits: list[list[float]] | None = None) -> tuple[Path, str]:
    wl = width_logits or [[-3.0, -3.0], [3.0, -3.0], [-3.0, -3.0]]     # two-word spans are "person"
    doc = {"format": "pgw-ml-labels/1", "task": "span-classification", "labels": SPAN_LABELS,
           "max_width": max_width, "max_words": max_words, "max_length": max_length, "threshold": 0.5,
           "ent_token": "<<ENT>>", "sep_token": "<<SEP>>",
           "special_tokens": {"cls": "[CLS]", "sep": "[SEP]", "pad": "[PAD]"}}
    return _write(d, span_model(max_width, wl), doc)


def detector_profile(d: Path, sha: str, **kw) -> dict:
    """An `ml_detector` profile entry for a model made by make_token_model."""
    cfg = {"path": str(d), "sha256": sha, "backend": "token", "labels": {"PER": "PERSON", "LOC": "IGNORE"},
           "min_score_by_type": {"DEFAULT": 0.5}, "workers": 0, "queue_max": 4, "timeout_s": 5.0,
           "intra_op_threads": 1, "inter_op_threads": 1, "batch_size": 4}
    cfg.update(kw)
    return cfg


def gate_profile(d: Path, sha: str, **kw) -> dict:
    cfg = {"path": str(d), "sha256": sha, "labels": list(GATE_LABELS), "workers": 0, "queue_max": 4,
           "timeout_s": 5.0, "intra_op_threads": 1, "inter_op_threads": 1, "batch_size": 4}
    cfg.update(kw)
    return cfg


# --- worker-pool test factories (imported by name in spawned worker processes) ---------------------------------

class _Slow:
    def __init__(self, seconds: float):
        self.seconds = seconds

    def warm(self) -> None:
        return None

    def detect_many(self, texts):
        if any("slow" in t for t in texts):
            time.sleep(self.seconds)
        return [[] for _ in texts]

    def classify_many(self, texts):
        if any("slow" in t for t in texts):
            time.sleep(self.seconds)
        return [{"health": 0.0} for _ in texts]


def slow_detector(seconds: float) -> _Slow:
    return _Slow(seconds)


class _Crash(_Slow):
    def detect_many(self, texts):
        if any("crash" in t for t in texts):
            os._exit(3)
        if any("raise" in t for t in texts):
            raise RuntimeError("inference blew up")
        return [[] for _ in texts]


def crash_detector() -> _Crash:
    return _Crash(0)


def failing_factory():
    raise RuntimeError("model does not load")
